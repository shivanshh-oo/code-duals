class Command(BaseCommand):
    help = 'Seed the database with sample problems (30-35 test cases each) including 6 placement problems.'

    def handle(self, *args, **options):
        created_count = 0
        updated_count = 0
        for pdata in PROBLEMS_DATA:
            problem = Problem.objects.filter(title=pdata['title'], source_url__isnull=True).first()
            is_new = False
            if not problem:
                problem = Problem.objects.create(
                    title=pdata['title'],
                    statement=pdata['statement'],
                    category=pdata['category'],
                    difficulty=pdata['difficulty'],
                    difficulty_rating=pdata['difficulty_rating'],
                    time_limit_sec=pdata['time_limit_sec'],
                    is_placement=pdata.get('is_placement', False),
                    is_draft=False,
                )
                is_new = True
                created_count += 1
            else:
                problem.statement = pdata['statement']
                problem.category = pdata['category']
                problem.difficulty = pdata['difficulty']
                problem.difficulty_rating = pdata['difficulty_rating']
                problem.time_limit_sec = pdata['time_limit_sec']
                problem.is_placement = pdata.get('is_placement', False)
                problem.is_draft = False
                problem.save()
                updated_count += 1

            problem.test_cases.all().delete()
            TestCase.objects.bulk_create([
                TestCase(
                    problem=problem,
                    input=tc['input'],
                    expected_output=tc['expected_output'],
                    is_sample=tc['is_sample'],
                )
                for tc in pdata['tests']
            ])

            sol = pdata['solution']
            Solution.objects.update_or_create(
                problem=problem,
                defaults={
                    'explanation': sol['explanation'],
                    'reference_code': sol['reference_code'],
                }
            )

            sample_count = sum(1 for tc in pdata['tests'] if tc['is_sample'])
            hidden_count = len(pdata['tests']) - sample_count
            action_label = "Created" if is_new else "Updated"
            self.stdout.write(f"  {action_label}: {pdata['title']} ({len(pdata['tests'])} tests: {sample_count} sample, {hidden_count} hidden)")

        self.stdout.write(self.style.SUCCESS(f'\nDone! {created_count} created, {updated_count} updated.'))
